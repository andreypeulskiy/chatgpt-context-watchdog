'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..', 'src');
const actions = fs.readFileSync(path.join(root, 'ui/15-panel-action-handlers.js'), 'utf8');
const composer = fs.readFileSync(path.join(root, 'chatgpt/09-dom-composer-state.js'), 'utf8');
const render = fs.readFileSync(path.join(root, 'ui/16-panel-rendering.js'), 'utf8');
assert.doesNotMatch(actions, /\bonConversationEvent\b/, 'Diagnostic copy cannot run conversation coordinator');
assert.match(actions, /readComposerControlsForDiagnostics\(\)/, 'Copy must sample controls without scanning messages');
assert.match(actions, /renderDiagnostics\(stats\(state\), state, \{/, 'Copy must update report from read-only snapshot');
const sample = composer.match(/function readComposerControlsForDiagnostics\(\)\s*\{([\s\S]*?)\n  \}/);
assert.ok(sample, 'Missing read-only composer control sampler');
assert.match(sample[1], /anyVisibleControl\(COMPOSER_CONTROLS\.stop\)/);
assert.match(sample[1], /anyVisibleControl\(COMPOSER_CONTROLS\.send\)/);
assert.doesNotMatch(sample[1], /collectMessageNodes|scanMessages|localStorage|setLastUiSignals|setTimeout|fetch/);
assert.match(render, /function renderDiagnostics\(s, state, signal = lastUiSignals\)/);
assert.doesNotMatch(render, /\bqueuePanelDialogFit\b/, 'Dialog refit must use shared layout observer');
console.log('PASS Diagnostics copy uses read-only controls and shared dialog lifecycle');
